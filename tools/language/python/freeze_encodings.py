#!/usr/bin/env python3
"""@brief Freeze real CPython startup encodings using the freshly built matching native VM.

@details This maintenance generator creates genuine CPython marshal code objects.
It is never invoked by ordinary Xmake application packaging. The complete Python
implementations and their deterministic logical filenames remain unchanged.
"""

import argparse
import marshal
from pathlib import Path
import sys


def main():
    """@brief Generate the five admitted frozen startup modules with exact native semantics.

    @return None after a complete new private C header is saved.
    @details A different interpreter implementation, version or existing output is refused.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if sys.platform != "linux" or sys.implementation.name != "cpython" or sys.version_info[:3] != (3, 14, 8):
        parser.error("Use the freshly built native CPython 3.14.8 inside the isolated SSH Linux container")
    if args.out.exists():
        parser.error("Generate startup encodings only into a new private output")
    modules = [("encodings", "__init__.py", True)] + [
        ("encodings." + name, name + ".py", False) for name in ("aliases", "utf_8", "ascii", "latin_1")
    ]
    header = ["/** @brief Genuine CPython frozen startup encodings; generated by matching 3.14.8. */"]
    entries = []
    for index, (name, file, package) in enumerate(modules):
        body = (args.source / "Lib/encodings" / file).read_bytes()
        code = marshal.dumps(compile(body, "/__uwvm_frozen__/" + name + ".py", "exec", dont_inherit=True))
        identifier = "sdk_code_" + str(index)
        header.append("static unsigned char const " + identifier + "[] = {")
        for offset in range(0, len(code), 24):
            header.append("    " + ",".join(map(str, code[offset : offset + 24])) + ",")
        header.append("};")
        entries.append(
            '    {"' + name + '", ' + identifier + ", sizeof(" + identifier + "), " + str(int(package)) + "},"
        )
    header += ["static struct _frozen const sdk_frozen[] = {", *entries, "    {NULL, NULL, 0, 0}", "};", ""]
    args.out.write_text("\n".join(header))


if __name__ == "__main__":
    main()
