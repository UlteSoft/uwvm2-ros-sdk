local sdk = os.getenv("UWVM_ROS_SDK_ROOT") or path.absolute("../../../../..", os.scriptdir())
includes(path.join(sdk, "tools/xmake/ros.lua"))
includes(path.join(sdk, "tools/shared/xmake/upstream_component.lua"))
includes(path.join(sdk, "tools/shared/ros_joint_fixture/xmake.lua"))
set_policy("run.autobuild", false)
set_policy("test.return_zero_on_failure", false)

local pid = path.join(sdk, "src/platform/ros2/control_toolbox")
target("universal_robots-original-control-toolbox-pid")
    uwvm_upstream_component({sdk_root = sdk, component_root = pid})
    set_wasm_kind("static")
    set_language("cpp")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("eh")
    add_includedirs(path.join(pid, "include"), path.join(pid, "third_party"), {public = true})
    add_defines("FMT_HEADER_ONLY", {public = true})
    add_cxxflags("-ffp-contract=off", "-Wno-error=deprecated-literal-operator", {force = true})
    add_files(path.join(pid, "pid.cpp"), path.join(pid, "pid_c.cpp"))
target_end()
local trajectory = path.join(sdk, "src/platform/ros2/joint_trajectory")
target("universal_robots-original-joint-trajectory")
    uwvm_upstream_component({sdk_root = sdk, component_root = trajectory})
    set_wasm_kind("static")
    set_language("cpp")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("eh")
    add_includedirs(path.join(trajectory, "include"), path.join(trajectory, "third_party"), {public = true})
    add_cxxflags("-ffp-contract=off", {force = true})
    add_files(path.join(trajectory, "trajectory.cpp"), path.join(trajectory, "trajectory_c.cpp"))
target_end()
target("universal_robots-official-webots")
    set_kind("binary")
    set_language("c")
    set_ros_platform("ros")
    set_ros2_version("jazzy")
    set_ros_scenario("official_ros_communication")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("eh")
    add_files("main.c")
    add_deps("universal_robots-original-control-toolbox-pid", "universal_robots-original-joint-trajectory")
    uwvm_ros_joint_fixture({sdk_root = sdk, driver = "control_fixture.py", config_environment = "UWVM_ROS_UNIVERSAL_ROBOTS_WEBOTS_TEST_CONFIG"})
target_end()
