local sdk = os.getenv("UWVM_ROS_SDK_ROOT")
if not sdk then raise("Set UWVM_ROS_SDK_ROOT") end
includes(path.join(sdk,"tools/xmake/ros.lua"))
set_policy("test.return_zero_on_failure",false)
target("shared_owner")
    set_kind("shared")
    set_language("wat")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1-threads")
    set_arch("wasm32")
    set_wasm_entry("freestanding")
    set_wasm_exceptions("noeh")
    set_wasm_features({"threads"})
    add_files("owner.wat")
target_end()
local function command(name,language,file)
    target(name)
        set_kind("binary")
        set_language(language)
        set_ros_platform("wasi")
        set_plat("wasm-wasip1-threads")
        set_arch("wasm32")
        set_wasm_entry("freestanding")
        set_wasm_exceptions("noeh")
        set_wasm_features({"threads","bulk-memory"})
        set_wasm_memory_import("env","memory")
        add_deps("shared_owner",{inherit=false})
        add_cxflags("-O1",{force=true})
        add_ldflags("-Wl,--initial-memory=2097152","-Wl,--max-memory=4194304",{force=true})
        add_files(file)
    target_end()
end
command("c_threaded_counter","c","main.c")
command("cpp_threaded_counter","cpp","main.cpp")
target("threaded_cfamily_tests")
    set_kind("phony")
    set_toolchains("ros.wasm.command")
    add_deps("shared_owner","c_threaded_counter","cpp_threaded_counter")
    add_tests("thread-stack-authority",{group="host-permissions"})
    uwvm_register_required_test("thread-stack-authority","host-permissions")
    on_test(function(target,opt)
        local python=import("python_runtime",{rootdir=path.join(sdk,"tools/xmake"),anonymous=true}).resolve()
        local vm=os.getenv("UWVM_ROS_THREAD_TEST_VM")
        assert(vm and path.is_absolute(vm) and os.isfile(vm),"Set UWVM_ROS_THREAD_TEST_VM")
        local output=path.join(target:dependir(),"thread-tests",path.filename(os.tmpfile({ramdisk=false})))
        local stdout,stderr=os.iorunv(python,{path.join(target:scriptdir(),"test_threads.py"),"--vm",vm,
            "--wasm-c",path.absolute(target:dep("c_threaded_counter"):targetfile()),
            "--wasm-cpp",path.absolute(target:dep("cpp_threaded_counter"):targetfile()),
            "--owner",path.absolute(target:dep("shared_owner"):targetfile()),"--output",path.absolute(output)},
            {curdir=target:scriptdir(),timeout=180000})
        opt.stdout,opt.stderr=stdout,stderr
        return true
    end)
target_end()
