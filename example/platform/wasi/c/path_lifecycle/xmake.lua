local sdk = os.getenv("UWVM_ROS_SDK_ROOT")
if not sdk then raise("Set UWVM_ROS_SDK_ROOT") end
includes(path.join(sdk,"tools/xmake/ros.lua"))
includes(path.join(sdk,"tools/shared/xmake/simulation_example.lua"))
set_policy("test.return_zero_on_failure",false)
target("path_lifecycle")
    set_kind("binary")
    set_language("c")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("noeh")
    add_files("main.c")
target_end()
target("path_lifecycle_tests")
    set_kind("phony")
    set_toolchains("ros.wasm.command")
    add_deps("path_lifecycle")
    add_tests("path-authority",{group="host-permissions"})
    uwvm_register_required_test("path-authority","host-permissions")
    on_test(function(target,opt)
        local python=import("python_runtime",{rootdir=path.join(sdk,"tools/xmake"),anonymous=true}).resolve()
        local vm=os.getenv("UWVM_ROS_FILE_TEST_VM")
        assert(vm and path.is_absolute(vm) and os.isfile(vm),"Set UWVM_ROS_FILE_TEST_VM")
        local output=path.join(target:dependir(),"file-tests",path.filename(os.tmpfile({ramdisk=false})))
        local argv={path.join(target:scriptdir(),"test_paths.py"),"--vm",vm,"--wasm",path.absolute(target:dep("path_lifecycle"):targetfile()),"--architecture","wasm32","--output",path.absolute(output)}
        local stdout,stderr=os.iorunv(python,argv,{curdir=target:scriptdir(),timeout=300000})
        opt.stdout,opt.stderr=stdout,stderr
        return true
    end)
target_end()
