local sdk = os.getenv("UWVM_ROS_SDK_ROOT") or path.absolute("../../../../..", os.scriptdir())
includes(path.join(sdk, "tools/xmake/ros.lua"))
includes(path.join(sdk, "tools/shared/xmake/wasi_component.lua"))
set_policy("run.autobuild", false)
set_policy("test.return_zero_on_failure", false)

local angles = path.join(sdk, "src/platform/ros2/angles/upstream")
local gtest = path.join(sdk, "src/testing/googletest")
local function common_cpp(kind)
    set_wasm_kind(kind)
    set_language("cpp")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("noeh")
    add_cxxflags("-ffp-contract=off", {force = true})
end
target("angles-test-framework")
    common_cpp("static")
    add_includedirs(gtest, path.join(gtest, "include"), {public = true})
    add_defines("_WASI_EMULATED_SIGNAL", "GTEST_NO_LLVM_SUPPORT=1", "GTEST_HAS_PTHREAD=0", "GTEST_HAS_FILE_SYSTEM=0",
        "GTEST_HAS_STREAM_REDIRECTION=0", "GTEST_HAS_POSIX_RE=0", {public = true})
    add_files(path.join(gtest, "src/gtest-all.cc"))
target_end()
target("angles-original-cpp-tests")
    common_cpp("binary")
    add_includedirs(path.join(angles, "include"))
    add_files(path.join(angles, "test/utest.cpp"))
    add_deps("angles-test-framework")
    add_links("wasi-emulated-signal")
    uwvm_wasi_component({api_version = 1, sdk_root = sdk, manifest = "component.json"})
target_end()
