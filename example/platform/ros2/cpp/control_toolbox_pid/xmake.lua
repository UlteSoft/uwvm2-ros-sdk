local sdk = os.getenv("UWVM_ROS_SDK_ROOT") or path.absolute("../../../../..", os.scriptdir())
includes(path.join(sdk, "tools/xmake/ros.lua"))
includes(path.join(sdk, "tools/shared/xmake/upstream_component.lua"))
includes(path.join(sdk, "tools/shared/xmake/wasi_component.lua"))
set_policy("run.autobuild", false)
set_policy("test.return_zero_on_failure", false)
local component = path.join(sdk, "src/platform/ros2/control_toolbox")
local function common(kind)
    set_wasm_kind(kind)
    set_language("cpp")
    set_ros_platform("wasi")
    set_plat("wasm-wasip1")
    set_arch("wasm32")
    set_wasm_exceptions("eh")
    add_includedirs(path.join(component, "include"), path.join(component, "third_party"), {public = true})
    add_defines("FMT_HEADER_ONLY", {public = true})
    add_cxxflags("-ffp-contract=off", "-gline-tables-only", "-Wno-error=deprecated-literal-operator", {force = true})
end
target("upstream-control-toolbox-pid")
    uwvm_upstream_component({sdk_root = sdk, component_root = component})
    common("static")
    add_files(path.join(component, "pid.cpp"), path.join(component, "pid_c.cpp"))
target_end()
target("pid-migration")
    common("binary")
    add_files("main.cpp")
    add_deps("upstream-control-toolbox-pid")
    uwvm_wasi_component({api_version = 1, sdk_root = sdk, manifest = "component.json"})
target_end()
