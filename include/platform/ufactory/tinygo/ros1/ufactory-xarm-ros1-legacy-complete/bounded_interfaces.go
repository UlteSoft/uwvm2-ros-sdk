func rpcError(code uint32) error      { return ros.Error{Code: code} }
func rpcID(bytes []byte) (uint64, error) {
	if len(bytes) < 8 {
		return 0, rpcError(ros.Invalid)
	}
	id := binary.LittleEndian.Uint64(bytes)
	if id == 0 {
		return 0, rpcError(ros.Invalid)
	}
	return id, nil
}
func rpcFrame(id uint64, kind int, body []byte) []byte {
	prefix := 8
	if kind >= 0 {
		prefix = 9
	}
	wire := make([]byte, prefix+len(body))
	binary.LittleEndian.PutUint64(wire, id)
	if kind >= 0 {
		wire[8] = byte(kind)
	}
	copy(wire[prefix:], body)
	return wire
}
func rpcIndex(values []uint64, id uint64) int {
	for i, value := range values {
		if value == id {
			return i
		}
	}
	return -1
}
func rpcRemove(values *[]uint64, id uint64) {
	i := rpcIndex(*values, id)
	if i >= 0 {
		last := len(*values) - 1
		(*values)[i] = (*values)[last]
		(*values)[last] = 0
		*values = (*values)[:last]
	}
}
func rpcOwns(values []uint64, id uint64) error {
	if id == 0 || rpcIndex(values, id) < 0 {
		return rpcError(ros.BadHandle)
	}
	return nil
}

// Pointer state is shared by every accidental facade value copy. Capabilities
// stay private, so a callback cannot bypass this owner lease through Node/Session.
// Use one caller-driven execution context; this is not a goroutine-safe scheduler.
type rpcOwners struct {
	caps     []*ros.Capability
	busy     bool
	capacity int
}

func rpcOpen(aliases []string, capacity int) (*rpcOwners, error) {
	o := &rpcOwners{capacity: capacity}
	fail := func(err error) (*rpcOwners, error) {
		return nil, &RPCOpenError{Primary: err, Rollback: o.cleanup(err, false)}
	}
	if capacity < 1 || capacity > 1024 || len(aliases) == 0 {
		return fail(rpcError(ros.Invalid))
	}
	for i, alias := range aliases {
		if alias == "" || len(alias) > 255 || strings.IndexByte(alias, 0) >= 0 {
			return fail(rpcError(ros.Invalid))
		}
		for _, old := range aliases[:i] {
			if old == alias {
				return fail(rpcError(ros.Invalid))
			}
		}
	}
	if ros.RawAbiVersion() != 1 {
		return fail(rpcError(ros.Unsupported))
	}
	for _, alias := range aliases {
		cap, err := ros.Open(alias)
		if err != nil {
			return fail(err)
		}
		o.caps = append(o.caps, cap)
	}
	return o, nil
}
func (o *rpcOwners) idle() error {
	if o == nil || len(o.caps) == 0 {
		return rpcError(ros.BadHandle)
	}
	if o.busy {
		return rpcError(ros.Conflict)
	}
	_, err := o.caps[0].RawHandle()
	return err
}
func (o *rpcOwners) cleanup(primary error, revoke bool) RPCCleanup {
	r := RPCCleanup{Primary: primary}
	if o == nil {
		return r
	}
	if o.busy {
		r.Results = []error{rpcError(ros.Conflict)}
		return r
	}
	for i := len(o.caps) - 1; i >= 0; i-- {
		if _, err := o.caps[i].RawHandle(); err == nil {
			if revoke {
				r.Results = append(r.Results, o.caps[i].Revoke())
			} else {
				r.Results = append(r.Results, o.caps[i].Close())
			}
		}
	}
	return r
}
func (o *rpcOwners) request(index int, op ros.Operation, wire []byte, maximum int) ([]byte, error) {
	if o == nil || index < 0 || index >= len(o.caps) {
		return nil, rpcError(ros.BadHandle)
	}
	out := make([]byte, maximum)
	n, err := o.caps[index].Request(op, wire, out)
	if err != nil {
		return nil, err
	}
	return out[:int(n)], nil
}
func (o *rpcOwners) zero(index int, op ros.Operation, wire []byte) error {
	out, err := o.request(index, op, wire, 0)
	if err != nil {
		return err
	}
	if len(out) != 0 {
		return rpcError(ros.Invalid)
	}
	return nil
}
func (o *rpcOwners) poll(maximum int) ([]byte, error) {
	out := make([]byte, maximum)
	n, err := o.caps[0].Poll(out)
	if err != nil {
		return nil, err
	}
	return out[:int(n)], nil
}

