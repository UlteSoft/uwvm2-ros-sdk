func (a *rpcAction) send(wire []byte) (uint64, error) {
	if err := a.owners.idle(); err != nil {
		return 0, err
	}
	if len(a.goals) == a.owners.capacity {
		return 0, rpcError(ros.TooLarge)
	}
	out, err := a.owners.request(0, ros.OpActionSendGoal, wire, 8)
	if err != nil {
		return 0, err
	}
	if len(out) != 8 {
		return 0, rpcError(ros.Invalid)
	}
	id, err := rpcID(out)
	if err != nil {
		return 0, err
	}
	if rpcIndex(a.goals, id) >= 0 {
		return 0, rpcError(ros.Invalid)
	}
	a.goals = append(a.goals, id)
	return id, nil
}
func (a *rpcAction) cancel(id uint64, any bool) (bool, error) {
	if err := a.owners.idle(); err != nil {
		return false, err
	}
	index, op := 1, ros.OpActionCancelOwnGoal
	if any {
		if len(a.owners.caps) != 5 {
			return false, rpcError(ros.Denied)
		}
		index, op = 4, ros.OpActionCancelAnyGoal
	} else if err := rpcOwns(a.goals, id); err != nil {
		return false, err
	}
	out, err := a.owners.request(index, op, rpcFrame(id, -1, nil), 1)
	if err != nil {
		return false, err
	}
	if len(out) != 1 || out[0] > 1 {
		return false, rpcError(ros.Invalid)
	}
	return out[0] == 1, nil
}
func (a *rpcAction) receive(id uint64, result bool, maximum int) ([]byte, uint8, error) {
	if err := a.owners.idle(); err != nil {
		return nil, 0, err
	}
	if err := rpcOwns(a.goals, id); err != nil {
		return nil, 0, err
	}
	index, op, prefix := 2, ros.OpActionReceiveFeedback, 8
	if result {
		index, op, prefix = 3, ros.OpActionReceiveResult, 9
	}
	out, err := a.owners.request(index, op, rpcFrame(id, -1, nil), maximum+prefix)
	if err != nil {
		return nil, 0, err
	}
	actual, err := rpcID(out)
	if err != nil || actual != id || len(out) < prefix {
		return nil, 0, rpcError(ros.Invalid)
	}
	kind := uint8(1)
	if result {
		kind = out[8]
		if kind < 2 || kind > 4 {
			return nil, 0, rpcError(ros.Invalid)
		}
	}
	return out[prefix:], kind, nil
}
func (a *rpcAction) cleanup(primary error, revoke bool) RPCCleanup {
	r := a.owners.cleanup(primary, revoke)
	if !a.owners.busy {
		a.goals = nil
	}
	return r
}

