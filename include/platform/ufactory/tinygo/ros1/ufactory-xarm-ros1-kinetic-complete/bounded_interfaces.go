func (c *rpcService) call(wire []byte, maximum int) ([]byte, error) {
	if err := c.owners.idle(); err != nil {
		return nil, err
	}
	return c.owners.request(0, ros.OpServiceCall, wire, maximum)
}
func (c *rpcService) submit(wire []byte) (uint64, error) {
	if err := c.owners.idle(); err != nil {
		return 0, err
	}
	if len(c.owners.caps) != 2 {
		return 0, rpcError(ros.Denied)
	}
	if len(c.pending) == c.owners.capacity {
		return 0, rpcError(ros.TooLarge)
	}
	id, err := c.owners.caps[0].SubmitService(c.owners.caps[1], wire)
	if err != nil {
		return 0, err
	}
	if id == 0 || rpcIndex(c.pending, id) >= 0 {
		return 0, rpcError(ros.Invalid)
	}
	c.pending = append(c.pending, id)
	return id, nil
}

// completion reads exactly one existing SDK envelope. The concrete decoder
// commits/removes correlation only after its complete generated value validates.
func (c *rpcService) completion(maximum int) (uint64, []byte, uint32, error) {
	if err := c.owners.idle(); err != nil {
		return 0, nil, 0, err
	}
	if len(c.owners.caps) != 2 {
		return 0, nil, 0, rpcError(ros.Denied)
	}
	out := make([]byte, 64+maximum)
	n, err := c.owners.caps[1].PollEventV1(out)
	if err != nil {
		return 0, nil, 0, err
	}
	event, err := ros.DecodeUnifiedEvent(out[:int(n)])
	if err != nil {
		return 0, nil, 0, err
	}
	source, err := c.owners.caps[0].RawHandle()
	if err != nil {
		return 0, nil, 0, err
	}
	if event.Backend != c.backend ||
		event.Source != source ||
		c.sequence == ^uint64(0) ||
		event.Sequence != c.sequence+1 ||
		(c.sequence != 0 && (event.Instance != c.instance ||
			event.Session != c.session)) {
		return 0, nil, 0, rpcError(ros.Invalid)
	}
	c.sequence, c.instance, c.session = event.Sequence, event.Instance, event.Session
	if event.Kind == ros.EventResourceClosed {
		return 0, nil, 0, rpcError(ros.BadHandle)
	}
	if err := rpcOwns(c.pending, event.Correlation); err != nil {
		return 0, nil, 0, err
	}
	if event.Kind == ros.EventResourceError {
		return event.Correlation, nil, event.Error, nil
	}
	if event.Kind != ros.EventServiceResponse {
		return 0, nil, 0, rpcError(ros.Invalid)
	}
	return event.Correlation, event.Body, 0, nil
}
func (c *rpcService) cleanup(primary error, revoke bool) RPCCleanup {
	r := c.owners.cleanup(primary, revoke)
	if !c.owners.busy {
		c.pending = nil
	}
	return r
}

type rpcServer struct {
	owners *rpcOwners
	live   []uint64
	action bool
}

func rpcServerOpen(advertise, respond string, action bool, capacity int) (*rpcServer, error) {
	o, err := rpcOpen([]string{advertise, respond}, capacity)
	if err != nil {
		return nil, err
	}
	if action {
		err = o.zero(0, ros.OpActionAdvertise, nil)
	} else {
		err = o.caps[0].AdvertiseService()
	}
	if err != nil {
		return nil, &RPCOpenError{Primary: err, Rollback: o.cleanup(err, false)}
	}
	return &rpcServer{owners: o, action: action}, nil
}
func (s *rpcServer) poll(maximum int) (uint64, []byte, error) {
	if len(s.live) == s.owners.capacity {
		return 0, nil, rpcError(ros.TooLarge)
	}
	wire, err := s.owners.poll(maximum + 8)
	if err != nil {
		return 0, nil, err
	}
	id, err := rpcID(wire)
	if err != nil {
		return 0, nil, err
	}
	if rpcIndex(s.live, id) >= 0 {
		return 0, nil, rpcError(ros.Invalid)
	}
	return id, wire[8:], nil
}
func (s *rpcServer) respond(id uint64, kind int, wire []byte) error {
	if err := rpcOwns(s.live, id); err != nil {
		return err
	}
	op := ros.OpServiceRespond
	if s.action {
		if kind < 1 || kind > 4 {
			return rpcError(ros.Invalid)
		}
		op = ros.OpActionRespond
	} else if kind != -1 {
		return rpcError(ros.Invalid)
	}
	if err := s.owners.zero(1, op, rpcFrame(id, kind, wire)); err != nil {
		return err
	}
	if !s.action || kind != 1 {
		rpcRemove(&s.live, id)
	}
	return nil
}
func (s *rpcServer) cleanup(primary error, revoke bool) RPCCleanup {
	r := s.owners.cleanup(primary, revoke)
	if !s.owners.busy {
		s.live = nil
	}
	return r
}

